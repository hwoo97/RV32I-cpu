"""Generates the address files of the MCU from one table (fw/common/memmap.txt).

    python tools/gen_memmap.py           # check the table and (re)write the generated files
    python tools/gen_memmap.py --check   # only compare: exit 1 if a generated file is missing or out of date

Generated files (committed, so the school server needs no Python):
    rtl/<chapter>/mcu_memmap.vh   Verilog `define: base, size, mask, address width, hit test, APB slot
                                  (one copy in every MCU chapter folder: ch14a_mcu, ch06_exception, ...)
    fw/common/memmap.h            C #define: base and size
    fw/common/memmap.ld           linker MEMORY block for the 'mem' regions, symbols for 'area' regions

Table checks: unique names, size is a power of two, base is a multiple of size, top-level regions
(mem, bus) do not overlap, every APB slave is inside the APB window, all APB slaves have the same size,
APB slots are unique, every 'area' is inside one 'mem' region and areas do not overlap. See 03_chapters/ch14a_mcu/design.md sec. 2.3.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "fw", "common", "memmap.txt")
# every MCU chapter folder keeps its own copy (chapter folders are copied, not shared)
OUT_VHS = [os.path.join(ROOT, "rtl", ch, "mcu_memmap.vh") for ch in ("ch14a_mcu", "ch06_exception")]
OUT_H = os.path.join(ROOT, "fw", "common", "memmap.h")
OUT_LD = os.path.join(ROOT, "fw", "common", "memmap.ld")

HEADER = "generated by tools/gen_memmap.py from fw/common/memmap.txt - do not edit"


def fail(msg):
    sys.exit(f"gen_memmap: {msg}")


def parse_size(text, where):
    m = re.fullmatch(r"(0x[0-9a-fA-F]+|\d+)([KM]?)", text)
    if not m:
        fail(f"{where}: bad size '{text}'")
    value = int(m.group(1), 0) * {"": 1, "K": 1024, "M": 1024 * 1024}[m.group(2)]
    if value <= 0 or value & (value - 1):
        fail(f"{where}: size {text} is not a power of two")
    return value


def read_table(path):
    regions = []
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cols = line.split()
        where = f"{os.path.relpath(path, ROOT)} line {n}"
        if len(cols) < 4:
            fail(f"{where}: need 'name base size kind'")
        name, base, size, kind = cols[0], cols[1], cols[2], cols[3]
        opts = cols[4:]
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
            fail(f"{where}: name '{name}' must be upper case (A-Z, 0-9, _)")
        if kind not in ("mem", "bus", "apb", "area"):
            fail(f"{where}: kind '{kind}' must be mem, bus, apb or area")
        r = {"name": name, "base": int(base, 16), "size": parse_size(size, where), "kind": kind,
             "attr": "rwx", "sim": False, "where": where}
        for o in opts:
            if o == "sim":
                r["sim"] = True
            elif o.startswith("attr="):
                r["attr"] = o[5:]
            else:
                fail(f"{where}: unknown option '{o}'")
        if r["base"] % r["size"]:
            fail(f"{where}: base 0x{r['base']:08x} is not a multiple of size 0x{r['size']:x}")
        if r["base"] + r["size"] > 1 << 32:
            fail(f"{where}: region goes past 0xFFFFFFFF")
        regions.append(r)
    return regions


def check(regions):
    names = [r["name"] for r in regions]
    for nm in set(names):
        if names.count(nm) > 1:
            fail(f"name {nm} used twice")
    top = [r for r in regions if r["kind"] in ("mem", "bus")]
    for i, a in enumerate(top):
        for b in top[i + 1:]:
            if a["base"] < b["base"] + b["size"] and b["base"] < a["base"] + a["size"]:
                fail(f"{a['name']} and {b['name']} overlap")
    mems = [r for r in regions if r["kind"] == "mem"]
    areas = [r for r in regions if r["kind"] == "area"]
    for a in areas:
        if not any(m["base"] <= a["base"] and a["base"] + a["size"] <= m["base"] + m["size"] for m in mems):
            fail(f"{a['name']} (area) is not inside a mem region")
    for i, a in enumerate(areas):
        for b in areas[i + 1:]:
            if a["base"] < b["base"] + b["size"] and b["base"] < a["base"] + a["size"]:
                fail(f"{a['name']} and {b['name']} overlap")
    buses = [r for r in regions if r["kind"] == "bus"]
    apbs = [r for r in regions if r["kind"] == "apb"]
    if apbs:
        if len(buses) != 1 or buses[0]["name"] != "APB":
            fail("APB slaves need exactly one bus region named APB")
        bus = buses[0]
        slave_size = apbs[0]["size"]
        for s in apbs:
            if not (bus["base"] <= s["base"] and s["base"] + s["size"] <= bus["base"] + bus["size"]):
                fail(f"{s['name']} is outside the APB window")
            if s["size"] != slave_size:
                fail(f"{s['name']}: all APB slaves must have the same size")
        lsb = slave_size.bit_length() - 1
        msb = bus["size"].bit_length() - 2
        slots = {}
        for s in apbs:
            s["slot"] = (s["base"] >> lsb) & ((1 << (msb - lsb + 1)) - 1)
            if s["slot"] in slots:
                fail(f"{s['name']} and {slots[s['slot']]} use the same APB slot")
            slots[s["slot"]] = s["name"]
        return lsb, msb
    return None, None


def h32(v):
    return f"32'h{v >> 16:04X}_{v & 0xFFFF:04X}"


def gen_vh(regions, lsb, msb):
    out = [f"// {HEADER}",
           "// Memory map for the MCU address decoder (03_chapters/ch14a_mcu/design.md sec. 2)",
           "//   MM_<NAME>_BASE / _SIZE : region start and size in bytes",
           "//   MM_<NAME>_AW           : byte address bits inside the region (log2 size)",
           "//   MM_<NAME>_HIT(a)       : 1 when 32-bit address a is inside the region",
           "//   MM_<NAME>_SLOT         : APB slot number = a[MM_APB_SLOT_MSB:MM_APB_SLOT_LSB]",
           "`ifndef MCU_MEMMAP_VH", "`define MCU_MEMMAP_VH", ""]
    for r in regions:
        n, b, s = r["name"], r["base"], r["size"]
        mask = (0xFFFFFFFF ^ (s - 1)) & 0xFFFFFFFF
        note = f"{r['kind']}" + (", simulation only" if r["sim"] else "")
        out += [f"// {n} ({note})",
                f"`define MM_{n}_BASE    {h32(b)}",
                f"`define MM_{n}_SIZE    {h32(s)}",
                f"`define MM_{n}_AW      {s.bit_length() - 1}",
                f"`define MM_{n}_HIT(a)  ((({{a}}) & {h32(mask)}) == {h32(b)})".replace("{a}", "a")]
        if r["kind"] == "apb":
            out.append(f"`define MM_{n}_SLOT    4'd{r['slot']}")
        out.append("")
    if lsb is not None:
        out += ["// APB slot field of the address",
                f"`define MM_APB_SLOT_MSB {msb}",
                f"`define MM_APB_SLOT_LSB {lsb}", ""]
    out.append("`endif")
    return "\n".join(out) + "\n"


def gen_h(regions):
    out = [f"/* {HEADER} */",
           "/* Memory map for firmware (03_chapters/ch14a_mcu/design.md sec. 2)",
           "   Plain hex numbers (no 'u' suffix) so the file also works in assembly (.S) */",
           "#ifndef MEMMAP_H", "#define MEMMAP_H", ""]
    width = max(len(r["name"]) for r in regions) + 5
    for r in regions:
        note = "  /* simulation only */" if r["sim"] else ""
        out += [f"#define {r['name'] + '_BASE':<{width}} 0x{r['base']:08X}{note}",
                f"#define {r['name'] + '_SIZE':<{width}} 0x{r['size']:08X}"]
    out += ["", "#endif"]
    return "\n".join(out) + "\n"


def gen_ld(regions):
    mems = [r for r in regions if r["kind"] == "mem"]
    width = max(len(r["name"]) for r in mems) if mems else 0
    out = [f"/* {HEADER} */",
           "/* Linker memory regions; fw/common/link.ld includes this file */",
           "MEMORY", "{"]
    for r in mems:
        out.append(f"  {r['name']:<{width}} ({r['attr']}) : ORIGIN = 0x{r['base']:08X}, LENGTH = 0x{r['size']:08X}")
    out.append("}")
    areas = [r for r in regions if r["kind"] == "area"]
    if areas:
        out.append("/* areas reserved inside the memories (the linker scripts keep data and stack out of them) */")
        for r in areas:
            out += [f"{r['name']}_BASE = 0x{r['base']:08X};", f"{r['name']}_SIZE = 0x{r['size']:08X};"]
    return "\n".join(out) + "\n"


def main():
    check_only = "--check" in sys.argv[1:]
    regions = read_table(TABLE)
    lsb, msb = check(regions)
    vh = gen_vh(regions, lsb, msb)
    outputs = {p: vh for p in OUT_VHS}
    outputs.update({OUT_H: gen_h(regions), OUT_LD: gen_ld(regions)})
    stale = []
    for path, text in outputs.items():
        old = open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(path) else None
        if old == text:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check_only:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    if check_only:
        if stale:
            sys.exit("gen_memmap --check: out of date: " + ", ".join(stale) + " (run python tools/gen_memmap.py)")
        print("gen_memmap --check: all generated files are up to date")
    else:
        print(f"gen_memmap: {len(regions)} regions, "
              + (f"updated: {', '.join(stale)}" if stale else "no change"))


if __name__ == "__main__":
    main()
