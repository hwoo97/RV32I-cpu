"""Generates the ch6 chip top and the Innovus IO file from one pad table (rtl/ch06_exception/chip_pads.txt).

    python tools/gen_chip.py           # check the table and (re)write the generated files
    python tools/gen_chip.py --check   # only compare: exit 1 if a generated file is missing or out of date

Generated files (committed, so the school server needs no Python):
    rtl/ch06_exception/rv32i_chip.v   chip top: rv32i_mcu + one giolib045 pad instance per pad
    pnr/ch06_chip/rv32i_chip.io       Innovus IO file (pad order per side, corner cells)

Table checks: known side and kind, unique ports and pad names, bus widths match the core part-select,
every input of rv32i_mcu is driven, each GPIO bit used once. See 03_chapters/ch06_exception/chip.md.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "rtl", "ch06_exception", "chip_pads.txt")
OUT_V = os.path.join(ROOT, "rtl", "ch06_exception", "rv32i_chip.v")
OUT_IO = os.path.join(ROOT, "pnr", "ch06_chip", "rv32i_chip.io")
HEADER = "generated by tools/gen_chip.py from rtl/ch06_exception/chip_pads.txt - do not edit"

CELL = {"PI": "PADDI", "PO": "PADDO", "PB": "PADDB",
        "VDD": "PADVDD", "VSS": "PADVSS", "VDDIO": "PADVDDIOR", "VSSIO": "PADVSSIOR"}
POWER = ("VDD", "VSS", "VDDIO", "VSSIO")
SIDES = {"N": "top", "E": "right", "S": "bottom", "W": "left"}
CORNER_CELL = "padIORINGCORNER"

# rv32i_mcu ports: name -> (direction, width)  (GPIO_W = 16)
MCU_PORTS = {
    "clk": ("in", 1), "rst_n": ("in", 1),
    "imem_addr": ("out", 32), "imem_rdata": ("in", 32),
    "irom_addr": ("out", 32), "irom_rdata": ("in", 32),
    "ram_addr": ("out", 32), "ram_wstrb": ("out", 4), "ram_wdata": ("out", 32), "ram_rdata": ("in", 32),
    "gpio_in": ("in", 16), "gpio_out": ("out", 16), "gpio_oe": ("out", 16),
    "uart_rx": ("in", 1), "uart_tx": ("out", 1),
    "ext_irq": ("in", 1), "timer_irq": ("out", 1),
    "dbg_pc": ("out", 32), "trap": ("out", 1), "irq_taken": ("out", 1), "bus_err": ("out", 1),
}


def fail(msg):
    sys.exit(f"gen_chip: {msg}")


def parse_sel(text, where):
    """NAME or NAME[msb:lsb] or NAME[bit] -> (name, msb, lsb, is_bus)"""
    m = re.fullmatch(r"([A-Za-z_][A-Za-z0-9_]*)(?:\[(\d+)(?::(\d+))?\])?", text)
    if not m:
        fail(f"{where}: bad name '{text}'")
    if m.group(2) is None:
        return m.group(1), 0, 0, False
    msb = int(m.group(2))
    lsb = int(m.group(3)) if m.group(3) is not None else msb
    if msb < lsb:
        fail(f"{where}: [{msb}:{lsb}] must be [msb:lsb]")
    return m.group(1), msb, lsb, True


def read_table():
    pads, ports = [], {}
    for n, line in enumerate(open(TABLE, encoding="utf-8"), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        where = f"chip_pads.txt line {n}"
        cols = line.split()
        if len(cols) != 4:
            fail(f"{where}: need 'side port kind core'")
        side, port, kind, core = cols
        if side not in SIDES:
            fail(f"{where}: side '{side}' must be N, E, S or W")
        if kind not in CELL:
            fail(f"{where}: kind '{kind}' must be one of {', '.join(CELL)}")
        pname, pmsb, plsb, pbus = parse_sel(port, where)
        if kind in POWER:
            if core != "-" or pbus:
                fail(f"{where}: a power pad has no bus and core '-'")
            pads.append({"side": side, "kind": kind, "inst": pname, "port": None})
            continue
        cname, cmsb, clsb, cbus = parse_sel(core, where)
        width = pmsb - plsb + 1
        if (cmsb - clsb + 1) != width:
            fail(f"{where}: port width {width} != core width {cmsb - clsb + 1}")
        if kind == "PB":
            if cname != "gpio":
                fail(f"{where}: PB pads connect to gpio[...]")
        elif cname not in MCU_PORTS:
            fail(f"{where}: '{cname}' is not a rv32i_mcu port")
        else:
            d, w = MCU_PORTS[cname]
            if (kind == "PI") != (d == "in"):
                fail(f"{where}: {kind} pad on rv32i_mcu {d}put '{cname}'")
            if cmsb >= w:
                fail(f"{where}: {cname}[{cmsb}] is outside its width {w}")
        dirn = {"PI": "input", "PO": "output", "PB": "inout"}[kind]
        if pname in ports and (ports[pname]["dir"] != dirn):
            fail(f"{where}: port {pname} used with two directions")
        ports.setdefault(pname, {"dir": dirn, "bits": set(), "bus": pbus})
        for i in range(width):
            pbit, cbit = plsb + i, clsb + i
            if pbit in ports[pname]["bits"]:
                fail(f"{where}: {pname}[{pbit}] listed twice")
            ports[pname]["bits"].add(pbit)
            inst = f"PAD_{pname}_{pbit}" if pbus else f"PAD_{pname}"
            pads.append({"side": side, "kind": kind, "inst": inst, "port": pname, "pbit": pbit, "pbus": pbus,
                         "core": cname, "cbit": cbit, "cbus": cbus})
    return pads, ports


def check(pads, ports):
    names = [p["inst"] for p in pads]
    for nm in set(names):
        if names.count(nm) > 1:
            fail(f"pad name {nm} used twice")
    for pname, p in ports.items():
        if p["bus"] and p["bits"] != set(range(max(p["bits"]) + 1)):
            fail(f"port {pname}: bits must be 0..{max(p['bits'])} without gaps")
    # every core input bit must be driven exactly once (by a PI pad, a PB pad for gpio_in, or tied)
    driven = {}
    for p in pads:
        if p["kind"] == "PI":
            driven.setdefault(p["core"], set()).add(p["cbit"])
        if p["kind"] == "PB":
            driven.setdefault("gpio_in", set()).add(p["cbit"])
    for name, (d, w) in MCU_PORTS.items():
        if d == "in":
            got = driven.get(name, set())
            if got != set(range(w)):
                fail(f"rv32i_mcu input {name} not fully driven by pads (bits {sorted(set(range(w)) - got)})")


def ref(name, bit, bus):
    return f"{name}[{bit}]" if bus else name


def gen_v(pads, ports):
    o = [f"// {HEADER}", "`timescale 1ns/1ps", "",
         "// ch6 single-cycle MCU chip: rv32i_mcu surrounded by giolib045 IO pads",
         "// (03_chapters/ch06_exception/chip.md)",
         "//  - IMEM / DMEM are outside the chip; only the address bits [13:2] they use leave the chip,",
         "//    the data address bus is shared by IMEM (data-side read) and DMEM",
         "//  - GPIO uses bidirectional pads: A = gpio_out, OEN = ~gpio_oe (0 = drive), Y = gpio_in",
         "//  - Power pads have no logical ports (PADVDD, PADVSS: core; PADVDDIOR, PADVSSIOR: IO ring)",
         "//  - Corner and filler cells are added in Innovus (pnr/ch06_chip)",
         "module rv32i_chip ("]
    plist = []
    for pname, p in ports.items():
        rng = f"[{max(p['bits'])}:0] " if p["bus"] else ""
        plist.append(f"    {p['dir']:<6} {rng}{pname}")
    o.append(",\n".join(plist))
    o += [");", ""]
    o.append("    // -- rv32i_mcu ports --")
    for name, (d, w) in MCU_PORTS.items():
        o.append(f"    wire {f'[{w-1}:0] ' if w > 1 else ''}{name};")
    o += ["", "    rv32i_mcu u_mcu ("]
    o.append(",\n".join(f"        .{name:<10} ({name})" for name in MCU_PORTS))
    o += ["    );", "", "    wire [15:0] gpio_oen = ~gpio_oe;", "", "    // -- pads --"]
    for p in pads:
        cell = CELL[p["kind"]]
        if p["kind"] in POWER:
            o.append(f"    {cell:<9} {p['inst']} ();")
            continue
        pad = ref(p["port"], p["pbit"], p["pbus"])
        if p["kind"] == "PI":
            o.append(f"    {cell:<9} {p['inst']} (.PAD({pad}), .Y({ref(p['core'], p['cbit'], MCU_PORTS[p['core']][1] > 1)}));")
        elif p["kind"] == "PO":
            o.append(f"    {cell:<9} {p['inst']} (.A({ref(p['core'], p['cbit'], MCU_PORTS[p['core']][1] > 1)}), .PAD({pad}));")
        else:
            b = p["cbit"]
            o.append(f"    {cell:<9} {p['inst']} (.A(gpio_out[{b}]), .OEN(gpio_oen[{b}]), .PAD({pad}), .Y(gpio_in[{b}]));")
    o += ["endmodule", ""]
    return "\n".join(o)


def gen_io(pads):
    o = [f"# {HEADER}",
         "# Innovus IO file: pads of each side in table order (io_order default), corners added as physical cells",
         "(globals", "    version = 3", "    io_order = default", ")", "(iopad"]
    corners = {"topleft": "CORNER_TL", "topright": "CORNER_TR", "bottomleft": "CORNER_BL", "bottomright": "CORNER_BR"}
    for pos, inst in corners.items():
        o.append(f"    ({pos}")
        o.append(f'        (inst name="{inst}" cell="{CORNER_CELL}")')
        o.append("    )")
    for side, word in SIDES.items():
        o.append(f"    ({word}")
        for p in pads:
            if p["side"] == side:
                o.append(f'        (inst name="{p["inst"]}")')
        o.append("    )")
    o += [")", ""]
    return "\n".join(o)


def main():
    check_only = "--check" in sys.argv[1:]
    pads, ports = read_table()
    check(pads, ports)
    outputs = {OUT_V: gen_v(pads, ports), OUT_IO: gen_io(pads)}
    stale = []
    for path, text in outputs.items():
        old = open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(path) else None
        if old == text:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check_only:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    count = {s: sum(1 for p in pads if p["side"] == s) for s in SIDES}
    summary = ", ".join(f"{s} {c}" for s, c in count.items())
    if check_only:
        if stale:
            sys.exit("gen_chip --check: out of date: " + ", ".join(stale) + " (run python tools/gen_chip.py)")
        print(f"gen_chip --check: up to date ({len(pads)} pads: {summary})")
    else:
        print(f"gen_chip: {len(pads)} pads ({summary}); " + (f"updated: {', '.join(stale)}" if stale else "no change"))


if __name__ == "__main__":
    main()
